//relational or comparison operators
// > - more than
// < - less than
// >= - more than or equal to
// <= - less than or equal to
// == - equal to
// != - not equal to
var result1 = 11 > 5; // true
var result2 = 18 < 5; // false
var result3 = 12 >= 10; // true
var result4 = 14 <= 5; // false
var result5 = 15 == 10; // false
var result6 = 10 != 5; // true
console.log(result1);
console.log(result2);
console.log(result3);
console.log(result4);
console.log(result5);
console.log(result6);


// equality operators
// == - equal to
// === - equal value and equal type

var x = 15 == 10; // true
var y = 17 === 10; // false
console.log(x==10); // lose comparison
console.log(y===10); // strict comparison
